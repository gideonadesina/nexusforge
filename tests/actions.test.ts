import { describe, it, expect, beforeAll, afterAll } from "vitest";
import { readFileSync } from "node:fs";
import { seedEducationGraph, census, expectedCensus } from "../src/lib/graph/seed";
import { runAndPersistAnalysis } from "../src/lib/runs/analyse-and-persist";
import { listFindings } from "../src/lib/runs/persist";
import { RunAuthorizationError } from "../src/lib/runs/authz";
import {
  proposeActions,
  approveProposal,
  rejectProposal,
  getProposal,
  listProposals,
  listAuditEvents,
  listAuditEventsForProposal,
  InvalidTransitionError,
  proposalIdFor,
} from "../src/lib/actions/actions";
import { generateProposals, RULE_COVER_DIRECT, RULE_EVIDENCE_GAP } from "../src/lib/actions/rules";
import { ALLOWED_TRANSITIONS, APPROVAL_SEMANTICS } from "../src/lib/actions/types";
import { roQuery, closeDb } from "../src/lib/falkor/client";
import { SCENARIO_ROOT_ENTITY_ID } from "../src/domain/education/seed-data";
import { uniqueTestGraph, cleanupGraph } from "./helpers";
import type { RunAndPersistResult } from "../src/lib/runs/analyse-and-persist";

const graphName = uniqueTestGraph("actions");
let runA: RunAndPersistResult;
let runB: RunAndPersistResult;
let credsA: { analysisRunId: string; ownerToken: string };
let credsB: { analysisRunId: string; ownerToken: string };

beforeAll(async () => {
  await seedEducationGraph(graphName);
  runA = await runAndPersistAnalysis(graphName, SCENARIO_ROOT_ENTITY_ID);
  runB = await runAndPersistAnalysis(graphName, SCENARIO_ROOT_ENTITY_ID);
  credsA = { analysisRunId: runA.run.analysisRunId, ownerToken: runA.run.ownerToken };
  credsB = { analysisRunId: runB.run.analysisRunId, ownerToken: runB.run.ownerToken };
  await proposeActions(graphName, credsA, runA.analysis);
  await proposeActions(graphName, credsB, runB.analysis);
}, 240_000);

afterAll(async () => {
  await cleanupGraph(graphName);
  await closeDb();
});

describe("proposals are generated by deterministic rules", () => {
  it("is a pure function of the analysis", () => {
    const a = generateProposals(runA.analysis);
    const b = generateProposals(runA.analysis);
    expect(a).toEqual(b);
  });

  it("proposes only for direct dependencies on a fully evidenced seed", () => {
    const drafts = generateProposals(runA.analysis);
    expect(drafts.length).toBeGreaterThan(0);
    for (const d of drafts) {
      expect(d.ruleId).toBe(RULE_COVER_DIRECT);
    }
    const directCount = runA.analysis.impacted.filter(
      (e) => e.shortestPath.edgeHops === 1,
    ).length;
    expect(drafts.length).toBe(directCount);
  });

  it("produces no evidence-gap proposals when evidence is complete", () => {
    const drafts = generateProposals(runA.analysis);
    expect(drafts.some((d) => d.ruleId === RULE_EVIDENCE_GAP)).toBe(false);
  });

  it("is driven by the graph, not hardcoded entity ids", () => {
    const drafts = generateProposals(runA.analysis);
    const targets = new Set(drafts.map((d) => d.targetEntityId));
    for (const t of targets) {
      const e = runA.analysis.impacted.find((x) => x.entityId === t);
      expect(e, `${t} must be a real impacted entity`).toBeDefined();
      expect(e!.shortestPath.edgeHops).toBe(1);
    }
  });
});

describe("proposals are persisted and linked to real findings", () => {
  it("stores every proposal as PROPOSED with an ASSESSED claim", async () => {
    const proposals = await listProposals(graphName, runA.run.analysisRunId);
    expect(proposals.length).toBeGreaterThan(0);
    for (const p of proposals) {
      expect(p.state).toBe("PROPOSED");
      expect(p.claim).toBe("ASSESSED");
      expect(p.ruleId).toMatch(/@\d+$/);
      expect(p.decidedAt).toBeFalsy();
      expect(p.rationale.length).toBeGreaterThan(0);
    }
  });

  it("links each proposal to the finding that justifies it", async () => {
    const res = await roQuery<{ proposalId: string; findingId: string }>(
      graphName,
      `MATCH (p:ActionProposal)-[:PROPOSED_IN]->(r:AnalysisRun {analysisRunId:$id})
       MATCH (p)-[:ADDRESSES]->(f:Finding)
       RETURN p.proposalId AS proposalId, f.findingId AS findingId ORDER BY proposalId`,
      { params: { id: runA.run.analysisRunId } },
    );
    const proposals = await listProposals(graphName, runA.run.analysisRunId);
    expect(res.data.length).toBe(proposals.length);

    const findingIds = new Set((await listFindings(graphName, runA.run.analysisRunId)).map((f) => f.findingId));
    for (const row of res.data) {
      expect(findingIds.has(row.findingId)).toBe(true);
    }
  });

  it("retains evidence references through the finding", async () => {
    const proposals = await listProposals(graphName, runA.run.analysisRunId);
    const findings = await listFindings(graphName, runA.run.analysisRunId);
    for (const p of proposals) {
      const f = findings.find((x) => x.findingId === p.findingId)!;
      expect(f).toBeDefined();
      expect(f.evidenceSourceIds.length).toBeGreaterThan(0);
      expect(p.evidenceStatus).toBe(f.evidenceStatus);
      expect(p.supported).toBe(f.supported);
    }
  });

  it("links each proposal to its target entity", async () => {
    const res = await roQuery<{ c: number }>(
      graphName,
      `MATCH (p:ActionProposal)-[:PROPOSED_IN]->(r:AnalysisRun {analysisRunId:$id})
       MATCH (p)-[:TARGETS]->(e:Entity) WHERE e.id = p.targetEntityId
       RETURN count(p) AS c`,
      { params: { id: runA.run.analysisRunId } },
    );
    const proposals = await listProposals(graphName, runA.run.analysisRunId);
    expect(res.data[0]?.c).toBe(proposals.length);
  });

  it("is idempotent across repeated generation", async () => {
    const before = await listProposals(graphName, runA.run.analysisRunId);
    await proposeActions(graphName, credsA, runA.analysis);
    const after = await listProposals(graphName, runA.run.analysisRunId);
    expect(after.length).toBe(before.length);
    expect(after.map((p) => p.proposalId).sort()).toEqual(before.map((p) => p.proposalId).sort());
  }, 120_000);

  it("keeps proposals of different runs separate", async () => {
    const a = await listProposals(graphName, runA.run.analysisRunId);
    const b = await listProposals(graphName, runB.run.analysisRunId);
    expect(a.length).toBe(b.length);
    const aIds = new Set(a.map((p) => p.proposalId));
    for (const p of b) expect(aIds.has(p.proposalId)).toBe(false);
  });
});

describe("only PROPOSED -> APPROVED | REJECTED exist", () => {
  it("declares no transitions out of terminal states", () => {
    expect(ALLOWED_TRANSITIONS.APPROVED).toEqual([]);
    expect(ALLOWED_TRANSITIONS.REJECTED).toEqual([]);
    expect(ALLOWED_TRANSITIONS.PROPOSED.sort()).toEqual(["APPROVED", "REJECTED"]);
  });

  it("never persists a REVIEWED, EXECUTED or VERIFIED state", async () => {
    const res = await roQuery<{ state: string; c: number }>(
      graphName,
      `MATCH (p:ActionProposal) RETURN p.state AS state, count(p) AS c ORDER BY state`,
    );
    for (const row of res.data) {
      expect(["PROPOSED", "APPROVED", "REJECTED"]).toContain(row.state);
    }
  });
});

describe("approval is a decision, never an execution", () => {
  it("records the decision and returns executed: false", async () => {
    const target = (await listProposals(graphName, runA.run.analysisRunId))[0]!;
    const result = await approveProposal(graphName, credsA, target.proposalId, "demo approval");

    expect(result.executed).toBe(false);
    expect(result.fromState).toBe("PROPOSED");
    expect(result.toState).toBe("APPROVED");

    const after = await getProposal(graphName, target.proposalId);
    expect(after!.state).toBe("APPROVED");
    expect(after!.decidedBy).toBe("DEMO_RUN_OWNER");
    expect(after!.decidedAt).toBeTruthy();
  });

  it("labels the authority as a demo owner, not institutional authority", async () => {
    const approved = (await listProposals(graphName, runA.run.analysisRunId)).find(
      (p) => p.state === "APPROVED",
    )!;
    expect(approved.decidedBy).toBe("DEMO_RUN_OWNER");
    expect(APPROVAL_SEMANTICS.approvedDoesNotMean).toMatch(/NOT been executed/i);
  });

  it("stores no execution fields anywhere on the proposal", async () => {
    const res = await roQuery<{ k: string[] }>(
      graphName,
      `MATCH (p:ActionProposal) RETURN keys(p) AS k LIMIT 1`,
    );
    const keys = res.data[0]?.k ?? [];
    for (const forbidden of ["executedAt", "executionResult", "verifiedAt", "completedAt"]) {
      expect(keys).not.toContain(forbidden);
    }
  });

  it("rejects a proposal and records it", async () => {
    const target = (await listProposals(graphName, runA.run.analysisRunId)).find(
      (p) => p.state === "PROPOSED",
    )!;
    const r = await rejectProposal(graphName, credsA, target.proposalId, "not required");
    expect(r.toState).toBe("REJECTED");
    expect((await getProposal(graphName, target.proposalId))!.state).toBe("REJECTED");
  });
});

describe("invalid transitions fail", () => {
  it("refuses to approve an already-approved proposal", async () => {
    const approved = (await listProposals(graphName, runA.run.analysisRunId)).find(
      (p) => p.state === "APPROVED",
    )!;
    await expect(approveProposal(graphName, credsA, approved.proposalId)).rejects.toThrow(
      InvalidTransitionError,
    );
  });

  it("refuses to reject an already-approved proposal", async () => {
    const approved = (await listProposals(graphName, runA.run.analysisRunId)).find(
      (p) => p.state === "APPROVED",
    )!;
    await expect(rejectProposal(graphName, credsA, approved.proposalId)).rejects.toThrow(
      InvalidTransitionError,
    );
  });

  it("refuses to transition a proposal that does not exist", async () => {
    await expect(
      approveProposal(graphName, credsA, "no-such-proposal"),
    ).rejects.toThrow();
    const res = await roQuery<{ c: number }>(
      graphName,
      `MATCH (p:ActionProposal {proposalId:'no-such-proposal'}) RETURN count(p) AS c`,
    );
    expect(res.data[0]?.c).toBe(0);
  });

  it("leaves state untouched after an invalid transition", async () => {
    const approved = (await listProposals(graphName, runA.run.analysisRunId)).find(
      (p) => p.state === "APPROVED",
    )!;
    const before = await getProposal(graphName, approved.proposalId);
    await expect(approveProposal(graphName, credsA, approved.proposalId)).rejects.toThrow();
    expect(await getProposal(graphName, approved.proposalId)).toEqual(before);
  });
});

describe("authorization on transitions", () => {
  it("rejects a wrong owner token", async () => {
    const target = (await listProposals(graphName, runB.run.analysisRunId))[0]!;
    await expect(
      approveProposal(
        graphName,
        { analysisRunId: runB.run.analysisRunId, ownerToken: "wrong-token" },
        target.proposalId,
      ),
    ).rejects.toThrow(RunAuthorizationError);
    expect((await getProposal(graphName, target.proposalId))!.state).toBe("PROPOSED");
  });

  it("rejects a missing owner token", async () => {
    const target = (await listProposals(graphName, runB.run.analysisRunId))[0]!;
    await expect(
      approveProposal(
        graphName,
        { analysisRunId: runB.run.analysisRunId, ownerToken: "" },
        target.proposalId,
      ),
    ).rejects.toThrow(RunAuthorizationError);
    expect((await getProposal(graphName, target.proposalId))!.state).toBe("PROPOSED");
  });

  it("rejects Run A's token used on Run B's proposal", async () => {
    const target = (await listProposals(graphName, runB.run.analysisRunId))[0]!;
    await expect(
      approveProposal(
        graphName,
        { analysisRunId: runB.run.analysisRunId, ownerToken: runA.run.ownerToken },
        target.proposalId,
      ),
    ).rejects.toThrow(RunAuthorizationError);
    expect((await getProposal(graphName, target.proposalId))!.state).toBe("PROPOSED");
  });

  it("rejects Run A's credentials targeting Run B's proposal id", async () => {
    // Correct token, but the proposal belongs to another run: the
    // -[:PROPOSED_IN]-> hop must prevent the cross-run mutation.
    const target = (await listProposals(graphName, runB.run.analysisRunId))[0]!;
    await expect(approveProposal(graphName, credsA, target.proposalId)).rejects.toThrow();
    expect((await getProposal(graphName, target.proposalId))!.state).toBe("PROPOSED");
  });

  it("creates no audit event for any rejected attempt", async () => {
    const events = await listAuditEvents(graphName, runB.run.analysisRunId);
    expect(events).toEqual([]);
  });
});

describe("append-only audit", () => {
  it("creates exactly one audit event per successful transition", async () => {
    const proposals = await listProposals(graphName, runA.run.analysisRunId);
    const decided = proposals.filter((p) => p.state !== "PROPOSED");
    const events = await listAuditEvents(graphName, runA.run.analysisRunId);
    expect(events.length).toBe(decided.length);
  });

  it("records from/to state, actor and timestamp", async () => {
    const events = await listAuditEvents(graphName, runA.run.analysisRunId);
    expect(events.length).toBeGreaterThan(0);
    for (const e of events) {
      expect(e.fromState).toBe("PROPOSED");
      expect(["APPROVED", "REJECTED"]).toContain(e.toState);
      expect(e.eventType).toBe(
        e.toState === "APPROVED" ? "PROPOSAL_APPROVED" : "PROPOSAL_REJECTED",
      );
      expect(e.actor).toBe("DEMO_RUN_OWNER");
      expect(Number.isNaN(Date.parse(e.at))).toBe(false);
      expect(e.analysisRunId).toBe(runA.run.analysisRunId);
    }
  });

  it("creates no duplicate events when a transition is retried", async () => {
    const approved = (await listProposals(graphName, runA.run.analysisRunId)).find(
      (p) => p.state === "APPROVED",
    )!;
    const before = await listAuditEventsForProposal(graphName, approved.proposalId);
    expect(before.length).toBe(1);

    await expect(approveProposal(graphName, credsA, approved.proposalId)).rejects.toThrow();
    await expect(approveProposal(graphName, credsA, approved.proposalId)).rejects.toThrow();

    const after = await listAuditEventsForProposal(graphName, approved.proposalId);
    expect(after.length).toBe(1);
    expect(after).toEqual(before);
  }, 120_000);

  it("keeps state and audit consistent", async () => {
    const res = await roQuery<{ proposalId: string; state: string; toState: string }>(
      graphName,
      `MATCH (a:AuditEvent)-[:ABOUT_PROPOSAL]->(p:ActionProposal)
       RETURN p.proposalId AS proposalId, p.state AS state, a.toState AS toState
       ORDER BY proposalId`,
    );
    expect(res.data.length).toBeGreaterThan(0);
    for (const row of res.data) {
      expect(row.state).toBe(row.toState);
    }
  });

  it("has no audit event without a corresponding proposal", async () => {
    const res = await roQuery<{ c: number }>(
      graphName,
      `MATCH (a:AuditEvent) WHERE NOT (a)-[:ABOUT_PROPOSAL]->(:ActionProposal) RETURN count(a) AS c`,
    );
    expect(res.data[0]?.c).toBe(0);
  });

  it("has no decided proposal without an audit event", async () => {
    const res = await roQuery<{ c: number }>(
      graphName,
      `MATCH (p:ActionProposal) WHERE p.state <> 'PROPOSED'
         AND NOT (:AuditEvent)-[:ABOUT_PROPOSAL]->(p)
       RETURN count(p) AS c`,
    );
    expect(res.data[0]?.c).toBe(0);
  });
});

describe("organizational data and findings remain untouched", () => {
  it("leaves the seed census unchanged", async () => {
    expect(await census(graphName)).toEqual(expectedCensus());
  });

  it("does not alter findings when proposals are decided", async () => {
    const findings = await listFindings(graphName, runA.run.analysisRunId);
    for (const f of findings) {
      expect(f.verificationStatus).toBe("UNVERIFIED");
      expect(f.evidenceSourceIds.length).toBeGreaterThan(0);
    }
  });

  it("keeps proposal and audit data off organizational labels", async () => {
    const res = await roQuery<{ c: number }>(
      graphName,
      `MATCH (n:Entity) WHERE n:ActionProposal OR n:AuditEvent RETURN count(n) AS c`,
    );
    expect(res.data[0]?.c).toBe(0);
  });
});

describe("action handlers have no generic write access", () => {
  it("imports neither writeQuery nor dropGraph", () => {
    const src = readFileSync("src/lib/actions/actions.ts", "utf8");
    // Check real import statements only, not prose that happens to name them.
    const imports = [...src.matchAll(/^import[\s\S]*?from\s+"[^"]+";$/gm)].map((m) => m[0]);
    expect(imports.length).toBeGreaterThan(0);
    const importedSymbols = imports.join("\n");

    expect(importedSymbols).not.toMatch(/\bwriteQuery\b/);
    expect(importedSymbols).not.toMatch(/\bdropGraph\b/);
    // It must use the authorized mutation helper instead.
    expect(importedSymbols).toMatch(/withRunAuthorization/);
    // And there must be no dynamic import smuggling them in either.
    expect(src).not.toMatch(/await import\(/);
  });

  it("derives proposal ids deterministically from run, rule and entity", () => {
    expect(proposalIdFor("r1", "rule@1", "e1")).toBe("r1::rule@1::e1");
    expect(proposalIdFor("r1", "rule@1", "e1")).toBe(proposalIdFor("r1", "rule@1", "e1"));
    expect(proposalIdFor("r2", "rule@1", "e1")).not.toBe(proposalIdFor("r1", "rule@1", "e1"));
  });
});
